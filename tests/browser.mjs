import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const baseURL=process.env.BASE_URL||'http://127.0.0.1:48173';
const output=process.env.SCREENSHOT_DIR||'test-results';
await mkdir(output,{recursive:true});
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const page=await browser.newPage({viewport:{width:1440,height:1100},acceptDownloads:true});
page.setDefaultTimeout(10000);page.setDefaultNavigationTimeout(30000);
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto(baseURL,{waitUntil:'domcontentloaded'});
await page.locator('#kpiEuEtsVal').filter({hasText:'88,000'}).waitFor();
assert.match(await page.locator('#kpiFuelEuVal').innerText(),/237,191\.27/);
assert.equal(await page.locator('.lang-switch').evaluate(el=>el.getBoundingClientRect().right<=innerWidth),true);
await page.locator('#vesselSelect').selectOption('v3');
await page.locator('[data-tab="tab-sandbox"]').click();
assert.doesNotMatch(await page.locator('#optionCompareBody').innerText(),/107,135/);
await page.locator('#openAuditModalBtn').click();
assert.match(await page.locator('#auditSnapshotContent').innerText(),/FuelEU: €0\.00/);
const pending=page.waitForEvent('download');await page.locator('#downloadSnapshotBtn').click();
const download=await pending;await download.saveAs('test-results/snapshot.json');
const snapshot=JSON.parse(await readFile('test-results/snapshot.json','utf8'));
assert.equal(snapshot.comparison.baseline.fuelEu,0);assert.equal(snapshot.externalVerification,'not-performed');
await page.keyboard.press('Escape');
assert.equal(await page.locator('#auditModalBackdrop').evaluate(el=>el.open),false);
await page.locator('#resetTwinBtn').click();
await page.locator('[data-tab="tab-cockpit"]').click();
await page.waitForTimeout(600);await page.mouse.move(2,2);
await page.screenshot({path:`${output}/overview-desktop.png`,fullPage:true});
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(400);
assert.equal(await page.locator('.kpi-card').first().evaluate(el=>el.getBoundingClientRect().width>300),true);
await page.screenshot({path:`${output}/overview-mobile.png`,fullPage:true});
assert.deepEqual(errors,[]);
await writeFile('test-results/smoke-summary.json',JSON.stringify({scope:'one bounded page smoke check',baseline:true,surplus:true,snapshotExport:true,hiddenMapReset:true,desktopAndMobileLayout:true,pageErrors:errors},null,2));
await browser.close();console.log('Page smoke check passed; original materials and effects retained.');
